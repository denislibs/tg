import { useLayoutEffect, useRef } from 'react'
import { mountSolid } from './mountSolid.solid'

/**
 * React-хост Solid-острова. Та же форма, которой у нас уже монтируются
 * ванильные порты (`components/chat/VanillaFeed.tsx`): узел-хост объявлен
 * `display: contents`, чтобы не появляться в бокс-дереве и не ломать flex
 * родителя, а инстанс поднимается layout-эффектом и гасится в его cleanup.
 *
 * Пропы едут снимком на монтирование — и это выбор ИМЕННО этого хоста, а не
 * ограничение моста: с задачи 5.5 (`mountSolid`, план «карточка профиля на
 * Solid») мост умеет `update(patch)` поверх живого стора, но этот компонент
 * его не зовёт — `useLayoutEffect` ниже читает `propsRef.current` РОВНО один
 * раз, в момент монтажа. Реактивность внутри острова остаётся заботой самого
 * Solid-компонента (подписка на внешние сторы напрямую), а не механизмом
 * «продавить новый объект `props` через границу React → Solid» — так и было
 * задумано: остров не должен пересоздаваться на каждый рендер родителя
 * из-за нового объекта `props` (эта причина не изменилась). Смена
 * `component` по-прежнему пересоздаёт остров (зависимость эффекта); смена
 * `props` — по-прежнему нет. Потребителю, которому нужны живые пропы без
 * пересоздания острова, — звать `mountSolid` напрямую (как `UserInfoPanel.
 * tsx`), а не через этот хост.
 *
 * ── КОНТРАКТ: `component` обязан быть СТАБИЛЬНОЙ ССЫЛКОЙ ────────────────────
 * Он лежит в зависимостях эффекта, поэтому новая ссылка = новый остров:
 * `dispose()` старого, монтирование нового, потеря всего его состояния. Для
 * попапа это выглядит как самопроизвольный ремоунт на каждый рендер родителя.
 *
 * Инлайн-стрелка в JSX (`component={(p) => …}`) даёт новую ссылку КАЖДЫЙ раз —
 * так делать нельзя. Компонент объявляется на уровне модуля (обычный случай)
 * либо мемоизируется вызывающим. Требование именно такое, а не «ключевать
 * иначе», потому что разные компоненты И ДОЛЖНЫ давать разные острова: это не
 * оптимизация, а единственный корректный ответ на смену того, что рисуем.
 *
 * Контракт держит пин (`SolidIsland.test.tsx`): тот же компонент между
 * рендерами остров НЕ пересоздаёт, другой — пересоздаёт.
 */
export default function SolidIsland<P extends Record<string, unknown>>({
  component,
  props,
}: {
  // Возвращаемый тип — `unknown`, а не `JSX.Element`: этот файл собирается
  // React-рантаймом, и имя `JSX` здесь принадлежит React. Тип Solid-узла сюда
  // не затащить, не смешав два пространства имён.
  component: (props: P) => unknown
  props: P
}) {
  const hostRef = useRef<HTMLDivElement>(null)
  const propsRef = useRef(props)
  propsRef.current = props

  useLayoutEffect(() => {
    const host = hostRef.current
    if (!host) return
    // Единственное приведение во всём мосте, и оно ровно про это расхождение
    // пространств имён `JSX` (см. тип пропа выше), а не про обход типизации.
    // Узлы снимает сам dispose (`render` делает `element.textContent = ""`),
    // поэтому чистить хост здесь отдельно не нужно — это была бы мёртвая строка.
    // `update` из возврата моста здесь не используется — см. докблок выше
    // («выбор ИМЕННО этого хоста»): пропы едут снимком, а не живым патчем.
    return mountSolid(host, component as Parameters<typeof mountSolid<P>>[1], propsRef.current).dispose
  }, [component])

  return <div ref={hostRef} style={{ display: 'contents' }} />
}
