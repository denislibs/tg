// Данные, поднятые в main.tsx ещё до первого рендера React: критический RPC
// (me) стартует параллельно с загрузкой бандла/словаря. Хуки читают отсюда;
// заполняется через setBootData из main.tsx (в тестах остаётся null —
// компоненты работают на своих mock-managers).
//
// Fix (ревью Task 6, Important #1): поле `dialogs: Promise<Dialog[]>` отсюда
// снесено. Диалоговая половина `loadChats` ушла владельцу ещё в основной
// правке Task 6 (`managers.dialogs.fillMirror()`/`refresh()`) — единственный
// потребитель этого поля, `useAppBootstrap → loadChats(managers, prefetch)`,
// уже не читал `prefetch.dialogs`, только `prefetch.me`. Оставленное поле
// было мёртвым (структурная типизация TS молча проглатывала лишний ключ) и с
// фактически неверным комментарием — риск, что следующий разработчик
// «починит» несуществующий путь и вернёт диалоги в `loadChats`, то есть
// второй источник порядка, ради устранения которого затевалась вся программа
// (docs/superpowers/specs/2026-08-12-dialogs-ownership-and-virtual-list-design.md).
// `boot.ts::applyDialogsMirror` по-прежнему применяет диалоги к зеркалу СРАЗУ,
// синхронно в bootstrap() — этому не нужен отдельный промис в bootData.
import type { User } from '../core/managers/authManager'

export interface BootData {
  me: Promise<User | null>
  /**
   * Сетевой догон списка диалогов, запущенный boot'ом (`applyDialogsMirror`):
   * резолвится, когда ответ `/chats` УЖЕ применён к зеркалу; не отклоняется
   * никогда (офлайн/401 остаются на кэше владельца). Fix (финальное ревью,
   * Important #3): на нём висит сид презенса в `useAppBootstrap` — раньше он
   * читал зеркало сразу и на пустом кэше (смена аккаунта, очищенное хранилище,
   * вход в соседней вкладке) молча выходил без единой цели, оставляя сеанс без
   * онлайн-точек и «был(а) в сети». Заменил мёртвый `hydratedFromCache`:
   * скелетон списка решает по `loaded` (см. ChatList.tsx), флаг не читал никто.
   */
  dialogsReady: Promise<void>
  // Есть ли локальный session_token (IDB). По нему useAuthGate решает authed до
  // ответа сети (как tweb — auth из локального состояния), без промежуточного null.
  hasToken: boolean
  // Стартовали под passcode-локом: под ним НЕ префетчим me и не гидрируем
  // (RPC/WS не поднимаем до разблокировки). me здесь — пустышка; настоящую
  // загрузку useAppBootstrap/useAuthGate делают после unlock (runWhenUnlocked).
  locked: boolean
}

export let bootData: BootData | null = null

// Префетч действителен только для той активной сессии, при которой страница
// загрузилась. Пока сессия не менялась, флаг true.
let prefetchValid = true

export function setBootData(d: BootData): void {
  bootData = d
  prefetchValid = true
}

/**
 * Префетч старта страницы (`me`) — или `null`, если брать его нельзя.
 *
 * Единственный способ до него добраться: `bootData.me` напрямую читать
 * нельзя, потому что этот промис **одноразовый по смыслу, но не по коду**. Он
 * разрешён значением аккаунта, под которым страница ЗАГРУЗИЛАСЬ, и живёт до
 * перезагрузки, а `Shell` монтируется заново на каждое `authed: false → true`
 * (`App.tsx` рендерит его условно) — вместе с ним заново отрабатывает
 * `useAppBootstrap`. Второй раз тот же префетч уже врёт: активная сессия к
 * этому моменту другая, и `loadChats` записал бы в стор личность ПРОШЛОГО
 * аккаунта, затерев только что приехавший `rt:me` нового. Детерминированной
 * коррекции у этого нет.
 *
 * Достижимо двумя путями (оба пинятся, см. useAuthGate.test.tsx): кросс-табовым
 * — «добавить аккаунт» в соседней вкладке увёл эту на экран входа, затем там же
 * вошли под другим аккаунтом; и локальным, существовавшим и до появления
 * кадров, — логаут без остающихся аккаунтов (он намеренно обходится без
 * перезагрузки) и вход в той же жизни страницы.
 *
 * `locked` — отдельная причина отказа: под пасскодом префетч не делался вовсе,
 * там пустышка (см. BootData.locked).
 *
 * Снимка диалогов здесь нет (Fix, ревью Task 6, Important #1): та половина
 * `loadChats` снесена, диалогами владеет `dialogsManager` (`fillMirror()`/
 * `refresh()`), и `boot.ts::applyDialogsMirror` применяет их к зеркалу СРАЗУ,
 * синхронно внутри `bootstrap()`. `dialogsReady` — не снимок, а ПРОМИС уже
 * запущенного сетевого догона: он ровно так же одноразов (принадлежит сессии,
 * под которой страница загрузилась) и потому ходит тем же каналом, что `me`.
 */
export function bootPrefetch(): { me: Promise<User | null>; dialogsReady: Promise<void> } | null {
  if (!bootData || bootData.locked || !prefetchValid) return null
  return { me: bootData.me, dialogsReady: bootData.dialogsReady }
}

/**
 * Активная сессия сменилась — префетч прошлой жизни страницы больше не
 * действителен. Зовут обработчики переходов (`useAuthGate`): и уход
 * (`rt:logging_out`), и вход (`rt:logged_in`) одинаково означают, что токен под
 * страницей уже не тот, при котором префетч поднимали.
 */
export function invalidateBootPrefetch(): void {
  prefetchValid = false
}

/**
 * Стартовала ли страница под passcode-локом (Fix, повторное ревью финальной
 * волны). Нужно `useAppBootstrap`, чтобы после разблокировки закрыть пробел
 * зеркала диалогов: под локом `bootstrap()` пропускает `fillMirror()` целиком
 * (см. `client/boot.ts::fillDialogsMirror` — RPC не летят вовсе), значит
 * владелец (`dialogsManager`) ни разу не гидрировал зеркало ЭТОЙ вкладки.
 * Обычный `refresh()`, которым `useAppBootstrap` подтягивает диалоги на
 * тёплом релогине, тут не спасает: он публикует операцию, только если сеть
 * разошлась с памятью владельца (Important #4, `dialogsManager.setAll`), а
 * на аккаунте с нулём диалогов пустой ответ сети структурно совпадает с ещё
 * не гидрированным пустым кэшем — `chatsStore.loaded` остаётся `false`
 * навсегда, список висит на скелетоне. В отличие от `refresh()`,
 * `fillMirror()` объявляет `reset` БЕЗУСЛОВНО (см. докблок `fillMirror` в
 * `dialogsManager.ts`) — ровно то объявление пробела, которое пропустил
 * локнутый boot.
 *
 * Читает `bootData.locked` напрямую (не через `bootPrefetch()`, который для
 * ЛЮБОЙ причины отказа — лок или инвалидация тёплого релогина — одинаково
 * отдаёт `null`): здесь важна именно причина, тёплый релогин уже закрыт
 * прямым `refresh()` и своим тестом (`useAppBootstrap.dialogsGate.test.tsx`).
 */
export function bootWasLocked(): boolean {
  return bootData?.locked ?? false
}
