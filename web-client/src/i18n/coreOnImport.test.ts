// Ядро отвечает ПЕРЕВОДОМ СРАЗУ, а не после первой загрузки языка.
//
// Файл отдельный намеренно. В `index.test.ts` каждый тест начинается с
// `await loadLang('en')`, и этот `loadLang` сам наполняет ядро — то есть данные там не
// различают «ядро наполнено на импорте» и «ядро наполнено загрузкой». Мутация «снять
// `applyToCore` из создания хранилища» в том файле ВЫЖИЛА, и проверка переехала сюда,
// где загрузки языка нет вовсе.
//
// Пропуск не теоретический: ванильные подписи (`Button`, `Row`, `ButtonMenuItem`,
// кнопки попапов) строятся `i18n()` в момент создания узла, а он бывает раньше, чем
// догрузится чанк словаря, — на пустом ядре пользователь прочитал бы имя ключа.
import { describe, expect, it } from 'vitest'

import { i18n } from '@lib/langPack'

// Импорт ради побочного эффекта: создание хранилища языка — это и есть первое
// наполнение ядра. Ничего из модуля здесь не зовётся.
import '@/i18n'

describe('ядро наполнено уже импортом хранилища языка', () => {
  it('без единой загрузки языка `i18n()` отдаёт текст источника, а не имя ключа', () => {
    expect(i18n('ArchivedChats').textContent).toBe('Archived Chats')
    expect(i18n('Story.AddToProfile').textContent).toBe('Post to Profile')
  })
})
