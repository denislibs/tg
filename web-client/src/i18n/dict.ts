import type { LangPackKey, LangPackValue } from '../lang'

/**
 * ФОРМА ЗАПИСИ ПЕРЕВОДА — и ничего больше (задача 9).
 *
 * ── Чем `dict.*.ts` были и чем стали ───────────────────────────────────────
 * До задачи 9 соседние файлы (`dict.ru.ts` и четыре других) были ЧАНКАМИ
 * ПРИЛОЖЕНИЯ: `loaders` отсюда тянул их динамическим импортом, и строки на экран
 * приезжали из бандла. Теперь строки приезжают С СЕРВЕРА
 * (`lib/langPack.ts::getCacheLangPackAndApply` → `langpack.getLangPack`), поэтому
 * ни `loaders`, ни английского словаря-исключения (`en`), ни моста в старую форму
 * ключа (`legacyDict.ts`) здесь нет: у продукта на эти файлы не осталось ни одного
 * импорта, и в сборку они не попадают вовсе.
 *
 * Сами переводы никуда не делись — они ИСХОДНИК, из которого сервер набивает свою
 * таблицу: `backend/internal/langsource/langsource.go` читает `web-client/src/lang.ts`
 * и `src/i18n/dict.*.ts` тем же разбором, каким снят вшитый в бинарь снимок
 * (`langpack.gen.json`), а сторож `TestSnapshotMatchesDictionaries` краснеет, если
 * снимок отстал от файлов. Правка перевода — правка ЗДЕСЬ плюс `go run ./cmd/langpackgen`.
 *
 * ── Зачем тогда этот тип ───────────────────────────────────────────────────
 * Он единственное, что удерживает файлы-исходники в согласии с английским
 * источником: ключ, которого нет в `src/lang.ts`, не соберётся, а форма значения
 * обязана совпасть с источником — где у английского формы числа, там объект с
 * формами и у перевода. Проверяет это `tsc` на `satisfies LangPackDict` в конце
 * каждого файла, и проверяет по-прежнему: файлы остаются частью проекта, даже
 * перестав быть частью бандла.
 *
 * `typeof import(...)` — тип-импорт, он стирается: значение `lang` в бандл отсюда
 * не едет.
 */
type LangSource = typeof import('../lang')['default']
export type LangPackDict = {
  [K in LangPackKey]?: LangSource[K] extends string ? string : Exclude<LangPackValue, string>
}
