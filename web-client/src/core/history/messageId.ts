// src/core/history/messageId.ts
//
// ГРАНИЦА ДВУХ ПРОСТРАНСТВ ИДЕНТИФИКАТОРОВ СООБЩЕНИЯ — порт tweb
// `appMessagesIdsManager.ts`.
//
// На проводе у сообщения ОДНО число: `message.id` — номер внутри чата
// (`docs/readiness/tl-message-analysis.md`, решение Р1). Идентичность это пара
// «пир + номер», и наружу выходит только она.
//
// У КЛИЕНТА пространство номеров своё и намеренно ШИРЕ серверного, потому что
// клиенту нужны идентификаторы, которых на сервере нет:
//
//   • неотправленный («отправляется…») бабл — он уже занял позицию внизу окна,
//     но номера ему ещё никто не назначил;
//   • синтетические строки ленты (плашка «Обсуждение началось», разделитель
//     даты) — они вообще не сообщения.
//
// Раньше границы не было: неотправленный бабл жил с ОТРИЦАТЕЛЬНЫМ id (`-seq`),
// синтетическая плашка — с ДРОБНЫМ `seq: 0.5`, и оба лежали в тех же полях, что
// настоящие номера. Наружу их не пускала только удача.
//
// Правильный порт — не «убрать дробь», а завести ОДНУ функцию приведения к
// серверному числу и провести через неё всё, что уходит на сервер. Ровно так
// устроен оригинал: клиентское число всегда больше `MESSAGE_ID_OFFSET`, поэтому
// утёкшее мимо приведения попадает в заведомо несуществующий номер и даёт
// ГРОМКИЙ промах (404), а не тихую подмену чужого сообщения.

/**
 * Порог клиентского пространства (tweb `MESSAGE_ID_OFFSET`). Любой клиентский
 * номер строго больше его, любой серверный — заведомо меньше: номера в чате
 * плотные и начинаются с единицы.
 */
export const MESSAGE_ID_OFFSET = 0xFFFFFFFF

/**
 * Шаг временного номера (tweb `generateTempMessageId` — `+ 0.0001`). Дробь, а
 * не «минус»: временный бабл стоит ПОСЛЕ последнего известного сообщения, и
 * сортировка окна по номеру обязана это сохранять. Отрицательное число ставило
 * бы его в начало истории.
 */
export const TEMP_MESSAGE_ID_INCREMENT = 0.0001

/**
 * Серверный номер → клиентский (tweb `generateMessageId`). Зовётся РОВНО НА
 * ГРАНИЦЕ разбора: `mapMessage` и всё, что приносит с провода чужой номер
 * (`dialog.top_message`, горизонты чтения, кадры read/pin/ack).
 */
export function generateMessageId(serverId: number): number {
  return MESSAGE_ID_OFFSET + serverId
}

/**
 * Клиентский номер → серверный (tweb `getServerMessageId`). Зовётся РОВНО НА
 * ГРАНИЦЕ отправки: URL ручек, тела запросов, поля кадров.
 *
 * Число, уже лежащее в серверном пространстве, возвращается как есть — так же,
 * как в оригинале: приведение идемпотентно, и вызвать его дважды безопаснее,
 * чем не вызвать ни разу.
 */
export function getServerMessageId(clientId: number): number {
  return clientId > MESSAGE_ID_OFFSET ? clientId - MESSAGE_ID_OFFSET : clientId
}

/**
 * Номер ВРЕМЕННОГО сообщения (tweb `generateTempMessageId`): дробь поверх
 * последнего занятого номера окна. Настоящим номером он не станет никогда —
 * его заменит эхо сервера (`finalizePendingMessage`).
 */
export function generateTempMessageId(afterId: number): number {
  return afterId + TEMP_MESSAGE_ID_INCREMENT
}

/**
 * Номер назначен КЛИЕНТОМ и на сервере не существует: временный бабл
 * (дробный) либо синтетическая строка ленты. Тот же вопрос, на который в tweb
 * отвечает `message.pFlags.is_outgoing` у неотправленного, — но здесь он
 * задаётся самому числу, потому что спрашивают его те, у кого объекта нет
 * (дедуп окна, гейты отправки).
 */
export function isLocalMessageId(id: number): boolean {
  return !Number.isInteger(id)
}
