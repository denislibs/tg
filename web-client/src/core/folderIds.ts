// Идентификаторы псевдо-папок — порт tweb `lib/appManagers/constants.ts:37-39`
// (`FOLDER_ID_ALL`/`FOLDER_ID_ARCHIVE`/`REAL_FOLDERS`).
//
// Единственный дом обеих констант: их читает и main (табы папок, счётчики,
// выбранный таб), и воркер (`dialogsManager.getDialogs({filterId})`), а вторая
// копия значения — второй источник правды о том, «какой список сейчас
// показывают». Модуль намеренно без зависимостей: воркеру нельзя импортировать
// UI-стор (`stores/foldersStore.ts`), это подняло бы в нём zustand-инстанс.
//
// Значения — id, которых НЕТ в пространстве пользовательских папок: их id
// раздаёт Postgres с единицы (`foldersrepo.go`).

/** «Все чаты» (tweb FOLDER_ID_ALL) — не архив, без фильтра. */
export const ALL_FOLDER_ID = 0

/**
 * «Архив» (tweb FOLDER_ID_ARCHIVE = 1).
 *
 * Отступление от tweb осознанное: там архив — РЕАЛЬНАЯ серверная папка с id 1
 * (пользовательские id у них начинаются с `START_LOCAL_ID = 2`), у нас же
 * архив — папка САМОГО ДИАЛОГА (`dialog.folder_id`, на проводе 0/1), а id
 * пользовательских папок раздаёт Postgres С ЕДИНИЦЫ — константа `1`
 * столкнулась бы с первой же созданной пользователем папкой. Отрицательное
 * значение в это пространство не попадает.
 */
export const ARCHIVE_FOLDER_ID = -1
