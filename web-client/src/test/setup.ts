// Общий сетап прогона.
//
// `lottie-web` невозможно вычислить под happy-dom: библиотека на СВОЁМ модульном
// инициализаторе создаёт канву и пишет в 2D-контекст, а happy-dom отдаёт на
// `getContext('2d')` → `null`. Получается `TypeError: Cannot set properties of
// null (setting 'fillStyle')` — незаловленное отклонение, которое не валит тест,
// но засоряет прогон и, как предупреждает сам vitest, «might cause false positive
// tests»: ошибка прилетает к случайному файлу, который в этот момент держит
// воркер, а не к тому, кто её породил. Отсюда и репутация «плавающей».
//
// Ловится это не импортом, а рантаймом: плеер грузится лениво
// (`components/lottie.ts::loadLottie`, ~521 kB отдельным чанком), и любой тест,
// который добирается до реального рендера анимации — уточки пустого состояния
// селектора, стикера, обезьянки пароля, — вычисляет модуль и падает. До сих пор
// с этим боролись поштучно: `PeerSelector.test.tsx` и `StickersHelper.suggest.
// test.ts` глушат каждый по-своему, и то же самое всплыло третьим файлом
// (`InputSearch.test.tsx` тянет `MemberPicker` → `PeerSelector` → уточка).
//
// Заглушка стоит на самом модуле, а не на канве: подменять `getContext` глобально
// значило бы менять поведение тестов, которые сознательно живут с `null`
// (`ChatBackground.test.tsx` — комментарий там прямо про это). Настоящего
// поведения `lottie-web` не проверяет ни один тест, поэтому терять здесь нечего.
// ── ПОЧЕМУ ЗДЕСЬ НЕТ `import '@/i18n'` ─────────────────────────────────────────
//
// Ядро локализации (`lib/langPack.ts`) наполняется побочным эффектом создания
// хранилища языка (`i18n/index.tsx::applyToCore`). В продукте этот импорт лежит на
// пути холодного старта (`main.tsx` → `client/boot.ts`), поэтому подписи `i18n()`
// пустого ядра не видят никогда; в прогоне же его приходится ставить ПОШТУЧНО в те
// тесты, что строят такие узлы (десять файлов). Соблазн поставить один импорт сюда
// очевиден — и он ПРОВЕРЕН, а не отвергнут по догадке:
//
//  • цена времени НЕ является причиной отказа. Первый замер («+80 с на прогон»)
//    был снят при load average 50+ и завышен кратно; честный, подвыборка `src/core`
//    (208 файлов), 3-5 прогонов: минимум 13.63 → 13.90 с, медиана ~14.1 → ~15.5 с,
//    то есть +2…10 %. Фаза `setup` растёт заметно (5.4 → 13.9 с), но она
//    параллельная и в стену прогона почти не переходит;
//  • причина отказа — ЛОМАЕТСЯ `vi.mock`. Сетап выполняется ДО модуля теста,
//    поэтому импорт отсюда инстанцирует `@lib/langPack` раньше, чем тест успевает
//    зарегистрировать моки, и внутри уже созданного `langPack` навсегда остаются
//    НАСТОЯЩИЕ зависимости. Проверено: с импортом здесь `lib/langPack.load.test.ts`
//    даёт 5 падений, `I18n.strings.size` на входе в тест = 1303 (тот же экземпляр,
//    что наполнил сетап), а замоканный `owner.cachedPack` НЕ ВЫЗЫВАЕТСЯ ни разу —
//    `startClient()` внутри langPack настоящий, падает под happy-dom, и `askOwner`
//    молча отдаёт `null`. Тест при этом мок видит: `vi.mock` сработал, просто не
//    для того экземпляра.
//
// Цена решения названа честно: ловушка для будущего теста, который построит узел
// `i18n()` и забудет импорт. Смягчение — сообщение пина на выдачу прямо называет
// эту причину второй (`domKeyLeak.ts`), и все десять нынешних случаев нашлись им.
import { vi } from 'vitest'

import { installDomKeyLeakPin } from './domKeyLeak'

vi.mock('lottie-web', () => {
  const anim = {
    play: vi.fn(),
    pause: vi.fn(),
    stop: vi.fn(),
    destroy: vi.fn(),
    goToAndStop: vi.fn(),
    goToAndPlay: vi.fn(),
    setSpeed: vi.fn(),
    setDirection: vi.fn(),
    addEventListener: vi.fn(),
    removeEventListener: vi.fn(),
  }
  const lottie = {
    loadAnimation: vi.fn(() => anim),
    setQuality: vi.fn(),
    destroy: vi.fn(),
    registerAnimation: vi.fn(),
  }
  return { default: lottie, ...lottie }
})

// Пин на утечку ключа в DOM — общий для всех компонентных тестов (см. `domKeyLeak.ts`).
installDomKeyLeakPin()
