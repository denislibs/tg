// ── ЯЗЫК В ПРОГОНЕ: строки из ФАЙЛОВ, а не из сети ─────────────────────────────
//
// В бою строки приезжают с сервера (`lib/langPack.ts::getCacheLangPackAndApply` →
// менеджер воркера → `GET /langpack/{code}`), и это правильно: словари живут на
// сервере, а не в бандле (задача 9). В прогоне сервера нет, воркера нет, а
// проверять надо НАСТОЯЩИЙ перевод — «5 уведомлений», а не фикстуру «%d foo»:
// перепутанные формы числа и потерянные строки видны только на живых данных.
//
// Поэтому здесь тот же ЕДИНСТВЕННЫЙ вход, каким пользуется бой
// (`I18n.applyLangPack` со слиянием «локальный английский ПОД пакетом»), но пакет
// собирается из файлов-исходников `src/i18n/dict.*.ts` — тех самых, из которых
// сервер набивает свою таблицу (`backend/internal/langsource`). То есть в прогоне
// применяются РОВНО ТЕ строки, которые в бою приедут по сети.
//
// ── Почему модуль тестовый, а не продуктовый ──────────────────────────────────
// Раньше эту роль играл `i18n/index.tsx::loadLang`: он тянул чанк словаря
// динамическим импортом, и его звали и продукт, и два десятка тестов. Именно
// поэтому у не-английского пользователя ехали лишние 18.5 кБ моста и ~25 кБ
// словаря — бандл вёз то, что нужно было только прогону. Разделение убрало это
// целиком: продукт спрашивает сервер, прогон читает файлы, общего кода — само
// применение.
import type { LangPackString } from '@layer'

import lang from '@/lang'
import I18n from '@lib/langPack'

/** Языки, у которых есть файл перевода. Английский — сам источник (`src/lang.ts`). */
const DICTS: Record<string, () => Promise<{ default: LangPackString[] }>> = {
  ru: () => import('@/i18n/dict.ru'),
  uk: () => import('@/i18n/dict.uk'),
  es: () => import('@/i18n/dict.es'),
  de: () => import('@/i18n/dict.de'),
  fr: () => import('@/i18n/dict.fr'),
}

/**
 * Применить язык так, как это делает бой. Порядок слоёв тот же, что в
 * `I18n.applyServerLangPack` (порт tweb :237-244): английский вниз, перевод
 * поверх — непереведённый ключ обязан падать на английский, а не на своё имя.
 *
 * `setLangCode` до применения — тоже как в бою (`getLangPackAndApply`): иначе
 * сверка `applyLangPack` («пакет не про текущий язык») отбросила бы пакет молча.
 */
export async function applyLang(code: string): Promise<void> {
  const strings = I18n.formatLocalStrings(lang)
  const load = DICTS[code]
  if (load) strings.push(...(await load()).default)
  I18n.setLangCode(code)
  I18n.applyLangPack({ _: 'langPackDifference', lang_code: code, from_version: 0, version: 1, strings })
}

/**
 * Английский СИНХРОННО, на импорте модуля.
 *
 * Это замена прежнему `import '@/i18n'` ради побочного эффекта. В бою ядро
 * наполняет старт (`client/boot.ts` дожидается `getCacheLangPackAndApply` до
 * первого кадра), в прогоне старта нет — а ванильные подписи (`Button`, `Row`,
 * `ButtonMenuItem`, кнопки попапов) строятся `i18n()` в момент создания узла и на
 * пустом ядре показали бы имя ключа. Тесту, который такой узел строит, достаточно
 * импортировать этот модуль.
 *
 * Отдельной функцией, а не `void applyLang('en')`: та асинхронна из-за импорта
 * словаря, а узел может быть построен в том же тике, что и импорт.
 */
function applyEnglish(): void {
  I18n.setLangCode('en')
  I18n.applyLangPack({
    _: 'langPackDifference',
    lang_code: 'en',
    from_version: 0,
    version: 0,
    strings: I18n.formatLocalStrings(lang),
  })
}

applyEnglish()
