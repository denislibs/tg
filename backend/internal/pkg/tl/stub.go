package tl

import (
	"errors"
	"fmt"
)

// Две ошибки формата, одинаковые для записи и разбора: тип `true` существует
// только как бит маски, а сама маска — не значение, а служебное поле провода.
var (
	errNakedTrue   = errors.New("тип true выражается битом маски и вне её невыразим")
	errMaskAsValue = errors.New("маска не является значением")
)

// writeStub пишет пустое значение объявленного типа.
//
// Заглушка — не «значение по умолчанию», а соблюдение РАСКЛАДКИ: обязательный
// параметр занимает своё место в потоке, потому что читающая сторона идёт по
// позициям, а не по именам. Решение «предмета нет» при этом не отменяется — мы
// по-прежнему не храним и не используем эти значения.
//
// Конструктору заглушки нет намеренно: «пустой конструктор» — это ВЫБОР из
// объединения (у `documentAttributeSticker.stickerset` таким выбором был бы
// `inputStickerSetEmpty`), и делать его молча за модель нельзя — она обязана
// назвать конструктор сама.
func writeStub(w *Writer, typ string) error {
	switch typ {
	case "int":
		w.Int(0)
	case "long":
		w.Long(0)
	case "double":
		w.Double(0)
	case "string":
		w.String("")
	case "bytes":
		w.Bytes(nil)
	case "Bool":
		w.Bool(false)
	default:
		return fmt.Errorf("заглушки для типа %s нет: пустое значение обязана назвать модель", typ)
	}
	return nil
}
