// UpdateDeclaresPts — объявляет ли конструктор кадра СВОЙ параметр `pts`.
//
// Курсор есть не у всех кадров, и это не пропуск схемы, а её деление.
// updateNewMessage двигает «ящик» сообщений и несёт pts параметром;
// updateMessageReactions, updateDialogPinned, updateNotifySettings,
// updateDraftMessage параметра pts не имеют ВОВСЕ — у оригинала такие кадры
// едут в контейнере updates, и порядок им задаёт seq КОНТЕЙНЕРА.
//
// У нас журнал один и курсор плотный, поэтому нести его обязаны все кадры. Но
// дописать pts в тело такого конструктора нельзя: это поле, которого в схеме
// нет, — кодек держит такое ошибкой (checkNoStrayFields), и на проводе TL оно
// сдвинуло бы разбор. Значит курсор едет в КОНВЕРТЕ — нашем аналоге контейнера.
//
// Ответ берётся из САМОЙ схемы (таблица кодека), а не из списка имён рядом с
// ней: список разъехался бы со схемой на первом же новом кадре. Неизвестный
// дискриминатор — ещё не портированный кадр (плоский словарь), у него курсор
// исторически лежит в теле, и менять это до порта незачем.
func UpdateDeclaresPts(predicate string) bool {
	c, ok := tl.ConstructorByPredicate(predicate)
	if !ok {
		return true
	}
	for _, prm := range c.Params {
		if prm.Name == "pts" {
			return true
		}
	}
	return false
}
