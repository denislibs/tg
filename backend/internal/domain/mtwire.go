package domain

import "github.com/messenger-denis/backend/internal/pkg/tl"

// Обязательные параметры схемы, которых мы сознательно не производим. Каждая
// строка — утверждение «предмета нет», а не забывчивость; развёрнутое основание
// стоит в докблоке соответствующего конструктора.
//
// Список читают ДВОЕ, и оба ответа обязаны быть одним:
//
//   - сверки модели со схемой (*_schema_test.go) — «пропуск назван, а не
//     проехал молча»;
//   - кодек TL (WireCodec) — «а что записано вместо».
//
// На JSON-проводе фазы 0 пропуск не стоил ничего: ключа нет — и всё. На проводе
// TL обязательный параметр занимает МЕСТО в потоке, читающая сторона идёт по
// позициям, и не записать его — значит сдвинуть все последующие поля и отдать
// чужому разбору мусор. Поэтому те же строки здесь означают ещё и «пишется
// пустое значение объявленного типа».
var OmittedWithoutSubject = map[string][]string{
	// Реквизиты MTProto-транспорта: файл адресуется числовым id через свой
	// эндпоинт (шапка mtmedia.go).
	"photo":    {"access_hash", "file_reference", "date", "dc_id"},
	"document": {"access_hash", "file_reference", "date", "dc_id"},
	// Тот же транспортный токен, но у точки на карте: картинку карты оригинал
	// просит у своего прокси с подписью, а у нас карту рисует клиент.
	"geoPoint": {"access_hash"},
	// Реквизиты СПРАВОЧНИКА мест (foursquare/gplaces): справочника у нас нет,
	// точку с подписью присылает сам отправитель.
	"messageMediaVenue": {"provider", "venue_id", "venue_type"},
	// Хэш для кэширования запроса; хэш-кэширования запросов у нас нет вовсе.
	"poll": {"hash"},
	// Внешность подарка у нас — unicode-символ (наш параметр emoji), а не
	// анимированный стикер: тот же случай, что emoji_status у пира.
	"starGift": {"sticker"},
	// Превью ссылки у нас — СНИМОК на сообщении, а не самостоятельный объект
	// хранилища: адресовать его нечем, и хэша кэша у запросов нет.
	"webPage": {"id", "hash"},

	// ── Наборы стикеров ─────────────────────────────────────────────────────
	// Токен доступа транспорта MTProto: набор адресуется числовым id.
	"stickerSet":        {"access_hash", "hash"},
	"inputStickerSetID": {"access_hash"},
	// «Не менялось» у REST выражают заголовки (ETag/304), а не поле тела
	// (tl-stickers-analysis.md, Р7).
	"messages.allStickers":      {"hash"},
	"messages.stickerSet":       {"hash"},
	"messages.recentStickers":   {"hash"},
	"messages.favedStickers":    {"hash"},
	"messages.featuredStickers": {"hash"},
	"messages.foundStickerSets": {"hash"},
	"messages.stickers":         {"hash"},
	"messages.savedGifs":        {"hash"},
}

// WireCodec — кодек TL, знающий наши заглушки.
//
// Больше кодеку про предметную область знать нечего: раскладку полей целиком
// диктует схема, а значения он берёт из самой модели по именам параметров.
var WireCodec = tl.NewCodec(OmittedWithoutSubject)
