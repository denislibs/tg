package domain

// Два ответа, которые не принадлежат ни одной подсистеме: «получилось» и
// «не получилось». Вместе они закрывают 664 витрины из 851 — почти четыре
// пятых всех ответов REST (разбор — docs/readiness/tl-rest-analysis.md).
//
// До сих пор оба были анонимными картами (`map[string]bool{"ok": true}`,
// `map[string]string{"error": msg}`), то есть значениями БЕЗ ТИПА. Кодек TL
// пишет только объявленное схемой, а сверки `*_schema_test.go` работают по
// типам Go — значит карту не проверял никто и записать её было нельзя.

// ── «Получилось» ───────────────────────────────────────────────────────────

const (
	BoolTrueTag  = "boolTrue"
	BoolFalseTag = "boolFalse"
)

// Bool — ответ действия.
//
// В оригинале это не заглушка и не признак недоделанной модели: `Bool`
// возвращают 212 из 790 методов схемы. Наше `{"ok": true}` расходилось с ним не
// смыслом, а тем, что было картой.
//
// Тип ОДИН на оба конструктора, хотя в схеме их два, — и это не то же самое,
// что «вид подделан значением поля». У `boolTrue` и `boolFalse` параметров нет
// вовсе, поэтому выбор конструктора и есть всё содержимое значения; выражен он
// дискриминатором `_`, то есть ровно тем, чем и положено.
type Bool struct {
	Underscore string `json:"_"`
}

// NewBool — «получилось» / «не получилось» выбором конструктора.
func NewBool(v bool) Bool {
	if v {
		return Bool{Underscore: BoolTrueTag}
	}
	return Bool{Underscore: BoolFalseTag}
}

// ── «Не получилось» ────────────────────────────────────────────────────────

const ErrorTag = "error"

// Error — тело ответа-ошибки.
//
// В оригинале ошибка НЕ витрина метода: она заменяет результат в транспорте
// (`rpc_error#2144ca19` из секции MTProto), и tweb ловит её в сетевом слое
// (`networker.ts:1948`) ещё до предметной модели. У нас эту позицию занимает
// статус HTTP — «замена результата» выражена транспортом так же.
//
// Телу остаётся объявленный тип, и берётся он из секции API:
// `error#c4b9f9bb code:int text:string = Error`. Конструктор в оригинале
// рудиментарен — его не возвращает ни один метод и не использует ни один
// параметр, — но предмет у него однозначен, он уже в таблице кодека, а завести
// рядом СВОЙ с тем же смыслом значило бы завести второе имя одного предмета.
//
// `code` дублирует статус HTTP намеренно: по проводу DNP ответ едет своим
// конвертом, и статус там — поле того конверта, а не строки протокола.
type Error struct {
	Underscore string `json:"_"`
	Code       int    `json:"code"`
	Text       string `json:"text"`
}

// NewError собирает тело ошибки.
func NewError(code int, text string) Error {
	return Error{Underscore: ErrorTag, Code: code, Text: text}
}
