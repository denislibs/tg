-- Служебка «X ограничил(а) права Y» (наш конструктор messageActionRestrict)
-- снята: у оригинала ограничение уходит только в журнал администратора, а
-- пилюля в общей ленте раскрывала всем читателям цель, автора, запреты и срок
-- (ревью #409 п. 1). Уже лежащие в истории — удалены мягко, как «удалить у
-- всех»: deleted_at, и действие снято, чтобы разбор не встречал конструктор,
-- которого больше нет. Повторяемая: строки с action IS NULL не совпадут.
UPDATE messages
   SET deleted_at = COALESCE(deleted_at, now()),
       action = NULL
 WHERE action->>'_' = 'messageActionRestrict';

