-- +goose Up
-- Кадр правки стал конструктором updateEditMessage, несущим сообщение ЦЕЛИКОМ.
-- Замороженные кадры СТАРОЙ формы удаляются, и это решение, а не небрежность.
--
-- Разбор — docs/readiness/tl-updates-analysis.md. Прежний кадр был ПАТЧЕМ
-- (id + текст + сущности + дата правки + разметка). Достроить из него целое
-- сообщение нельзя: в нём нет ни автора, ни даты отправки, ни вложения.
--
-- Достроить их join'ом с `messages` тоже нельзя честно: вложение в модели —
-- объединение MessageMedia, которое собирает доменный код по строке media, а не
-- SQL. Собранное «как получится» сообщение без вложения при переигрывании
-- ЗАМЕНИЛО бы у клиента сообщение с картинкой на сообщение без неё — то есть
-- миграция сама испортила бы данные ради формы.
--
-- Поэтому строки удаляются. Цена названа: правка, сделанная в пределах ОКНА
-- журнала (он и так подрезается до горизонта /sync), не будет переиграна тому,
-- кто всё это время был офлайн, — он увидит её при первой же загрузке истории,
-- потому что история отдаёт сообщение целиком и всегда актуальным.
--
-- Дыра в плотном курсоре при этом безопасна: путь /sync применяет строки строго
-- вперёд и пропущенный номер просто перешагивает, а живой путь на разрыве уходит
-- в догон, который приносит ту же выборку.

DELETE FROM updates
 WHERE type = 'edit_message'
   AND payload IS NOT NULL
   AND NOT (payload ? '_');

