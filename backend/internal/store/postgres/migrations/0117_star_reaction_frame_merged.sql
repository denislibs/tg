-- Платная ⭐-реакция перестала быть ОТДЕЛЬНЫМ кадром: она едет тем же
-- конструктором updateMessageReactions, что и обычная, — вторым конструктором
-- объединения Reaction (reactionPaid) в том же векторе results.
--
-- Разбор — docs/readiness/tl-updates-analysis.md (Р4, группа 2): «платная
-- реакция при этом не отдельный кадр: она внутри MessageReactions».
--
-- Замороженные кадры star_reaction УДАЛЯЮТСЯ, и это решение, а не небрежность.
-- Их тело — {id, sender_id, total, mine}, то есть ПОЛОВИНА агрегата: эмодзи-чипы
-- сообщения на тот момент в нём не сохранены и восстановить их нечем. Достроить
-- join'ом с `reactions` тоже нельзя честно — там СЕГОДНЯШНИЕ чипы, а не те, что
-- были на этом pts; переигрывание получило бы состояние из будущего.
--
-- А положить половину нельзя тем более: агрегат АБСОЛЮТЕН, и кадр без
-- эмодзи-чипов утверждает, что их не существует, — то есть стёр бы их
-- получателю. Ровно поэтому обе половины теперь собираются одним местом
-- (messageReactionsAggregate).
--
-- Цена названа: вклад звёздами, сделанный в пределах ОКНА журнала, не будет
-- переигран тому, кто всё это время был офлайн, — он увидит его при первой же
-- загрузке истории, потому что сообщение отдаётся с агрегатом целиком.
--
-- Остаток, который эта миграция НЕ чинит: кадры type='reaction', переписанные
-- миграцией 0116, несут только эмодзи-половину и тем самым утверждают «платных
-- реакций нет». Для сообщения, у которого они были, переигрывание уберёт
-- ⭐-чип до первой загрузки истории. Достроить их той же цены не выйдет — total
-- на тот момент в них не сохранён, — а удалять ВСЕ кадры реакций ради редкого
-- сочетания «эмодзи и звёзды на одном сообщении» дороже самой болезни.
--
-- Дыра в плотном курсоре безопасна: /sync применяет строки строго вперёд и
-- пропущенный номер перешагивает, а живой путь на разрыве уходит в догон.

