package demoseed

// Содержимое демо-стенда: тематические каналы с постами, обычные группы с
// перепиской. Тексты осмысленные и разной длины — на них проверяются лента,
// разметка, альбомы и служебные пилюли, поэтому «сообщение №17» тут не годится.

// post — одна публикация канала.
type post struct {
	body []run
	// photo — индекс картинки из набора канала (см. channelSpec.photos);
	// -1 — пост без вложения.
	photo int
}

func ps(runs ...run) post { return post{body: runs, photo: -1} }

func pf(idx int, runs ...run) post { return post{body: runs, photo: idx} }

// pollSpec — опрос, который сид отправляет в чат после основной ленты.
type pollSpec struct {
	question string
	options  []string
	quiz     bool
	correct  int
}

type channelSpec struct {
	title, username, about string
	creator                string // юзернейм автора канала
	photos                 int    // сколько картинок завести под этот канал
	pinIndex               int    // какой пост закрепить (-1 — не закреплять)
	poll                   *pollSpec
	posts                  []post
}

// reply — одна реплика групповой переписки.
type reply struct {
	author string
	body   []run
	// replyTo — индекс реплики в этом же скрипте, на которую отвечаем;
	// -1 — обычное сообщение.
	replyTo int
	// album — сколько картинок отправить одной медиагруппой вместо текста
	// (0 — текстовая реплика). Подпись альбома — тот же body.
	album int
}

func rp(author string, runs ...run) reply {
	return reply{author: author, body: runs, replyTo: -1}
}

func rpTo(author string, to int, runs ...run) reply {
	return reply{author: author, body: runs, replyTo: to}
}

func rpAlbum(author string, n int, runs ...run) reply {
	return reply{author: author, body: runs, replyTo: -1, album: n}
}

type groupSpec struct {
	title, about string
	creator      string
	members      []string // добавляются при создании (пилюля «создал группу»)
	lateJoin     []string // добавляются в середине переписки — каждый даёт свою пилюлю
	pinIndex     int
	poll         *pollSpec
	script       []reply
}

